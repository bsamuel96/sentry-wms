export function t(value) {
  if (typeof value !== 'string') return value;
  if (TEXT[value]) return TEXT[value];

  const loadMatch = value.match(/^Could not load (.+)\.$/i);
  if (loadMatch) {
    const subject = SUBJECTS[loadMatch[1].toLowerCase()] || loadMatch[1];
    return `Nu s-a putut încărca ${subject}.`;
  }

  const backMatch = value.match(/^Back to (.+)$/i);
  if (backMatch) return `Înapoi la ${t(backMatch[1])}`;

  return value;
}

export function statusLabel(status) {
  return STATUS[status] || status;
}

const LOCALIZED_ATTRIBUTES = ['aria-label', 'placeholder', 'title'];

function translateTextNode(node) {
  const value = node.nodeValue || '';
  const trimmed = value.trim();
  if (!trimmed) return;
  const translated = t(trimmed);
  if (translated === trimmed) return;
  node.nodeValue = value.replace(trimmed, translated);
}

function translateElement(element) {
  for (const attribute of LOCALIZED_ATTRIBUTES) {
    const value = element.getAttribute?.(attribute);
    if (!value) continue;
    const translated = t(value);
    if (translated !== value) element.setAttribute(attribute, translated);
  }
}

export function localizeTree(root) {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
  if (root.nodeType === Node.ELEMENT_NODE) translateElement(root);
  const walker = document.createTreeWalker(
    root,
    NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
  );
  let current = walker.nextNode();
  while (current) {
    if (current.nodeType === Node.TEXT_NODE) translateTextNode(current);
    else translateElement(current);
    current = walker.nextNode();
  }
}

export function installRomanianUi() {
  document.documentElement.lang = 'ro';
  localizeTree(document.body);
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') translateTextNode(mutation.target);
      for (const node of mutation.addedNodes) localizeTree(node);
    }
  });
  observer.observe(document.body, {
    childList: true,
    characterData: true,
    subtree: true,
  });
  return () => observer.disconnect();
}
